import { render, screen, waitFor } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { beforeEach, expect, it, vi } from "vitest";
import { createApiClient, type ApiClient } from "@/api/client";
import { mockFetchNoDelay } from "@/api/mock/handler";
import { resetCntsCal } from "@/api/mock/kn-cnts-cal";
import { DutyRosterScreen } from "./DutyRosterScreen";
import { createCntsCalApi, currentMonth } from "./api";
const auth: {api: ApiClient|null} = {api:null};
vi.mock("@/auth/AuthProvider",()=>({useAuth:()=>({api:auth.api,kn:{context:{role:"admin"}}})}));
vi.mock("next/navigation",()=>({usePathname:()=>"/kn/cnts/lich-truc",useRouter:()=>({push:vi.fn(),replace:vi.fn()})}));
beforeEach(()=>resetCntsCal());
it("CNTS-ROSTER-SCOPE-002: Admin chọn tỉnh trước khi tải; lịch chung cũ chỉ xem",async()=>{
 const calls:string[]=[];
 auth.api=createApiClient({baseUrl:"http://mock",getAccessToken:()=>"mock.setter",fetch:async(req)=>{
  calls.push(req.url);return mockFetchNoDelay(req);
 }});
 const user=userEvent.setup();
 render(<DutyRosterScreen/>);
 const selector=screen.getByRole("combobox",{name:"Tỉnh của lịch trực"});
 await screen.findByRole("option",{name:/An Giang/});
 expect(calls.filter(x=>x.includes("duty-rosters"))).toHaveLength(0);
 await user.selectOptions(selector,"91");
 await screen.findByRole("button",{name:"Thêm hàng"});
 expect(calls.some(x=>x.includes("province_code=91"))).toBe(true);
 await user.selectOptions(selector,"legacy");
 await waitFor(()=>expect(calls.some(x=>x.includes("province_code=legacy"))).toBe(true));
 await waitFor(()=>expect(screen.queryByRole("button",{name:"Thêm hàng"})).not.toBeInTheDocument());
 expect(screen.queryByRole("button",{name:/^Lưu/})).not.toBeInTheDocument();
});

it("BF-CN-DUTY: cột Địa chỉ/ĐT, tô ngày chưa có người trực, nạp Excel xem trước rồi lưu source=excel", async () => {
 auth.api=createApiClient({baseUrl:"http://mock",getAccessToken:()=>"mock.setter",fetch:async(req)=>mockFetchNoDelay(req)});
 const capi=createCntsCalApi(auth.api);
 const month=currentMonth();
 const r=await capi.roster(month,"91");
 const f=r.facilities[0]!.ref, o=r.officers[0]!.ref;
 await capi.saveRoster(month,{province_code:"91",base_version:0,cells:[{facility_ref:f,officer_ref:o,day:1,shift:"N"}]});
 const file=await capi.exportRoster(month,"91");
 const bytes=new Uint8Array(await file.blob.arrayBuffer());
 const user=userEvent.setup();
 render(<DutyRosterScreen/>);
 await screen.findByRole("option",{name:/An Giang/});
 await user.selectOptions(screen.getByRole("combobox",{name:"Tỉnh của lịch trực"}),"91");
 await screen.findByRole("button",{name:"Thêm hàng"});
 expect(screen.getByRole("columnheader",{name:"Địa chỉ"})).toBeInTheDocument();
 expect(screen.getByRole("columnheader",{name:"ĐT"})).toBeInTheDocument();
 expect(screen.getByText("0900•••001")).toBeInTheDocument();
 expect(screen.getByRole("button",{name:/ ngày 2: nghỉ \(cơ sở chưa có người trực\)$/})).toBeInTheDocument();
 expect(screen.getByRole("button",{name:/ ngày 1: N$/})).toBeInTheDocument();
 await user.upload(screen.getByLabelText("Tệp Excel lịch trực"),new File([bytes],"lich-truc.xlsx",{type:"application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"}));
 const preview=await screen.findByRole("region",{name:"Xem trước tệp nạp"});
 expect(preview).toHaveTextContent("1 dòng viên chức, 1 ô ca trực");
 expect(preview).toHaveTextContent("Không có lỗi.");
 await user.click(screen.getByRole("button",{name:"Áp dụng vào lưới"}));
 await user.click(screen.getByRole("button",{name:"Lưu"}));
 await waitFor(()=>expect(screen.getByRole("region",{name:"Lịch sử lưu"})).toHaveTextContent("nạp Excel"));
});

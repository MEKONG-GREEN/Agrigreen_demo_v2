import { describe, expect, it } from "vitest";
import { createApiClient } from "@/api/client";
import { mockFetchNoDelay } from "@/api/mock/handler";
import { ApiProblem } from "@/api/problem";
import { createKhtcPeriodApi } from "../periods/api";
import { createKhtcFormApi, emptyContent } from "../forms/api";
import { createReportApi, filterRows, type ReportRow } from "./api";
const client = () => createApiClient({ baseUrl: "http://mock", getAccessToken: () => "mock.tinh", getContextId: () => null, fetch: mockFetchNoDelay });
const code = (p: Promise<unknown>) => p.then(() => "ok", (e: unknown) => e instanceof ApiProblem ? e.problem.code : String(e));
describe("W11.66 report contract", () => {
    it("uses submitted sheets, keeps old download bytes, locks numeric inputs and requires provisional acknowledgement", async () => {
        const api = client(), periods = createKhtcPeriodApi(api), forms = createKhtcFormApi(api), reports = createReportApi(api);
        const p = await periods.open({ report_type: "week", year: new Date().getFullYear() + 4, no: 4, departments: ["trong_trot"] });
        const f = await forms.get(p.id, "trong_trot"), row = f.tabs.flatMap(t => t.rows).find(r => !r.module_sourced)!;
        const input = emptyContent();
        input.cells[row.entry_ref] = { done: "999" };
        await forms.draft(p.id, "trong_trot", input, 0);
        let d = await reports.get(p.id);
        expect(d.content.data.rows.find(r => r.ref === row.entry_ref)?.in_period).toBe("0");
        input.cells[row.entry_ref] = { done: "12" };
        input.texts.cong_tac_khac = "Thực hiện mô hình minh họa";
        await forms.submit(p.id, "trong_trot", input, 0);
        d = await reports.refresh(p.id, 0);
        expect(d.content.data.rows.find(r => r.ref === row.entry_ref)?.in_period).toBe("12");
        expect(await code(reports.export(p.id, d.version, false, {}))).toBe("extension.khtc_report_provisional");
        const first = await reports.export(p.id, d.version, true, {}), old = await (await reports.download(p.id, first.id)).blob.text();
        expect(old).toContain("12");
        expect(old).not.toContain("999");
        expect(await code(reports.final(p.id, first.id))).toBe("extension.khtc_report_provisional");
        d = await reports.save(p.id, { base_version: d.version, admin: { signer: "Người soạn" }, texts: { B: "Đánh giá riêng" } });
        expect(d.content.admin.signer?.override).toBe("Người soạn");
        const second = await reports.export(p.id, d.version, true, {});
        expect(second.version).toBe(2);
        expect(await (await reports.download(p.id, first.id)).blob.text()).toBe(old);
        expect((await reports.history(p.id)).map(x => x.version)).toEqual([2, 1]);
        expect(await code(reports.save(p.id, { base_version: d.version, texts: { "A.I.1": "1000000" } }))).toBe("extension.khtc_report_invalid");
        expect(await code(reports.save(p.id, { base_version: 0, texts: { B: "stale" } }))).toBe("extension.khtc_report_version_conflict");
        d = await reports.save(p.id, { base_version: d.version, admin: { signer: null } });
        expect(d.content.admin.signer?.override).toBeNull();
    });
    it("initializes only M5 section II from the previous program report and preserves a saved blank", async () => {
        const api = client(), periods = createKhtcPeriodApi(api), reports = createReportApi(api);
        const year = new Date().getFullYear() + 6;
        const open = (as_of_date: string) => periods.open({ report_type: "program", year, as_of_date, due_at: `${year}-12-31T03:00:00Z`, departments: ["trong_trot"] });
        const first = await open(`${year}-10-06`);
        await reports.save(first.id, { base_version: 0, texts: { I: "Đánh giá cũ", II: "Kế hoạch kỳ trước" } });
        const second = await open(`${year}-10-13`);
        let d = await reports.get(second.id);
        expect(d.content.texts.II).toBe("Kế hoạch kỳ trước");
        expect(d.content.texts.I).not.toBe("Đánh giá cũ");
        d = await reports.save(second.id, { base_version: 0, texts: { II: "" } });
        d = await reports.refresh(second.id, d.version);
        expect(d.content.texts.II).toBe("");
    });
    it("filters items by program, department and commune while preserving ancestors", () => {
        const row = (ref: string, kind: string, parent_ref: string | null, department = "", communes: string[] = []): ReportRow => ({ ref, kind, parent_ref, department, communes, program_ref: null, tab: "programs", roman: "", name: ref, unit: "ha", planned: "100", scale: "", in_period: "1", adjustment: "0", year_to_date: "2", percent: "2", level: "slow", status: "", content: "", people: "", budget: "", missing: false, source_key: "" });
        const rows = [row("p", "program", null), row("g", "group", "p"), row("i", "item", "g", "trong_trot", ["A"]), row("other", "item", "p", "trong_trot", ["B"]), row("q", "program", null)];
        expect(filterRows(rows, { program: "p", department: "trong_trot", commune: "A" }).map(r => r.ref)).toEqual(["p", "g", "i"]);
        expect(filterRows(rows, { commune: "absent" })).toEqual([]);
        expect(filterRows(rows, { level: "achieved" })).toEqual([]);
        expect(filterRows(rows, { level: "slow", commune: "A" }).map(r => r.ref)).toEqual(["p", "g", "i"]);
    });
});

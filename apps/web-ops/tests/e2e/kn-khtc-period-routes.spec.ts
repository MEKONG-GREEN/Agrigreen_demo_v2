import { expect, test } from "@playwright/test";
import { logout, sidebar } from "./helpers";

test("BF-SWEEP-KHTC-REST: mở kỳ trên route riêng, giữ nháp qua Back, Detail/Log và sửa hạn", async ({ page }) => {
  test.setTimeout(180_000);
  await page.clock.setFixedTime(new Date("2030-06-01T09:00:00Z"));
  await page.goto("/login");
  await page.getByLabel("Email hoặc số điện thoại").fill("admin.mekong@mekonggreen.vn");
  await page.getByLabel("Mật khẩu", { exact: true }).fill("KhuyenNong@2026");
  await page.getByRole("button", { name: "Đăng nhập", exact: true }).click();
  await sidebar(page).getByRole("link", { name: "Phòng ban", exact: true }).click();
  await page.getByLabel("Trạng thái Phòng Kế hoạch - Tài chính", { exact: true }).selectOption("active");
  await expect(page.getByRole("status").filter({ hasText: "Đã đổi" })).toBeVisible();
  // Tạo phân công thật trong mock qua Admin UI, không giả context hay sửa storage quyền.
  await sidebar(page).getByRole("link", { name: "Người dùng", exact: true }).click();
  await page.getByRole("link", { name: "Tạo tài khoản", exact: true }).click();
  const main = page.getByRole("main");
  await expect(main.getByRole("button", { name: "Lưu", exact: true })).toBeEnabled();
  await main.getByLabel("Họ tên").fill("Cán bộ KHTC kiểm thử 180");
  await main.getByLabel("Email").fill("khtc.period180@example.test");
  await main.getByLabel("Số điện thoại (tên đăng nhập)").fill("0912345690");
  const assignment = main.getByRole("group", { name: "Vai trò và phạm vi" });
  await assignment.getByRole("combobox", { name: "Vai trò", exact: true }).selectOption("kn_tinh");
  await assignment.getByRole("checkbox", { name: "trong_trot", exact: true }).uncheck();
  await assignment.getByRole("checkbox", { name: "ke_hoach_tai_chinh", exact: true }).check();
  await expect(main.getByLabel("Họ tên")).toHaveValue("Cán bộ KHTC kiểm thử 180");
  await main.getByRole("button", { name: "Lưu", exact: true }).click();
  await expect(page.getByRole("heading", { level: 1, name: "Cán bộ KHTC kiểm thử 180" })).toBeVisible();
  await logout(page);
  await page.getByLabel("Email hoặc số điện thoại").fill("0912345690");
  await page.getByLabel("Mật khẩu", { exact: true }).fill("KhuyenNong@2026");
  await page.getByRole("button", { name: "Đăng nhập", exact: true }).click();
  await expect(page).toHaveURL(/\/kn\/khtc\/ky-bao-cao$/);
  const list = page.getByRole("table", { name: "Danh sách kỳ báo cáo", exact: true });
  await expect(list.getByRole("columnheader", { name: "STT", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Mở kỳ", exact: true }).click();
  await expect(page).toHaveURL(/\/ky-bao-cao\/them-moi$/);
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await page.getByRole("combobox", { name: "Loại báo cáo", exact: true }).selectOption("month");
  await page.getByRole("combobox", { name: "Số kỳ", exact: true }).selectOption("12");
  await expect(page.getByLabel("Hạn xuất", { exact: true })).toHaveCount(0);
  await page.getByRole("link", { name: "Danh sách kỳ báo cáo", exact: true }).click();
  await expect(list).toBeVisible();
  await page.getByRole("button", { name: "Mở kỳ", exact: true }).click();
  await expect(page.getByRole("combobox", { name: "Loại báo cáo", exact: true })).toHaveValue("month");
  await expect(page.getByRole("combobox", { name: "Số kỳ", exact: true })).toHaveValue("12");
  await page.getByRole("button", { name: "Xem trước", exact: true }).click();
  await page.getByRole("button", { name: "Mở kỳ và giao phiếu", exact: true }).click();
  await expect(page).toHaveURL(/\/ky-bao-cao\/ky\/[^/]+$/);
  await expect(page.getByRole("complementary", { name: "Log", exact: true })).toContainText("Mở kỳ và giao");
  await expect(page.getByRole("table", { name: "Tiến độ nộp phiếu và nguồn module", exact: true }).getByRole("columnheader", { name: "STT", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Sửa hạn nộp", exact: true }).click();
  await expect(page).toHaveURL(/\/sua-han$/);
  await page.getByRole("textbox", { name: "Hạn nộp", exact: true }).fill("2031-01-03T10:00");
  await page.getByRole("textbox", { name: "Lý do", exact: true }).fill("Điều chỉnh lịch theo kế hoạch");
  await page.getByRole("button", { name: "Lưu", exact: true }).click();
  await expect(page).toHaveURL(/\/ky-bao-cao\/ky\/[^/]+$/);
  await expect(page.getByRole("complementary", { name: "Log", exact: true })).toContainText("Sửa hạn nộp");
});

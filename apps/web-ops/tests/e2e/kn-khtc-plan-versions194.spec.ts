import { expect, test } from "@playwright/test";
import { logout, sidebar } from "./helpers";

test("KHTC194: điều chỉnh theo QĐ trên route riêng, giữ nháp và xem đúng phiên bản", async ({ page }, info) => {
  test.setTimeout(180_000);
  await page.clock.setFixedTime(new Date("2030-06-01T09:00:00Z"));
  const login = async () => {
    await page.getByLabel("Email hoặc số điện thoại").fill("admin.mekong@mekonggreen.vn");
    await page.getByLabel("Mật khẩu", { exact: true }).fill("KhuyenNong@2026");
    await page.getByRole("button", { name: "Đăng nhập", exact: true }).click();
  };
  await page.goto("/login"); await login();
  await sidebar(page).getByRole("link", { name: "Phòng ban", exact: true }).click();
  await page.getByLabel("Trạng thái Phòng Kế hoạch - Tài chính", { exact: true }).selectOption("active");
  await expect(page.getByRole("status").filter({ hasText: "Đã đổi" })).toBeVisible();
  await logout(page); await login();
  await sidebar(page).getByRole("button", { name: "Phòng Kế hoạch - Tài chính", exact: true }).click();
  await sidebar(page).getByRole("link", { name: "Kế hoạch năm", exact: true }).click();
  await expect(page).toHaveURL(/\/ke-hoach-nam$/);
  const base = new URL(page.url()).pathname;
  const item = page.getByRole("row").filter({ hasText: "Mô hình lúa chất lượng cao" });
  await item.getByRole("button", { name: "Sửa", exact: true }).click();
  await page.getByRole("textbox", { name: /^Tên/ }).fill("Hạng mục kế hoạch194");
  await page.getByRole("button", { name: "Lưu vào nháp", exact: true }).click();
  await page.getByRole("button", { name: "Điều chỉnh theo QĐ", exact: true }).click();
  await expect(page).toHaveURL(/\/luu-phien-ban\?year=2030$/);
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await page.getByRole("button", { name: "Lưu phiên bản", exact: true }).click();
  const number = page.getByRole("textbox", { name: /Số quyết định/ });
  await expect(number).toHaveAttribute("aria-invalid", "true");
  await number.fill("QĐ194");
  await page.getByRole("textbox", { name: /Ngày quyết định/ }).fill("2030-06-01");
  await page.getByRole("textbox", { name: /Ngày hiệu lực/ }).fill("2030-07-01");
  await expect(number).not.toHaveAttribute("aria-invalid", "true");
  await expect(page.getByRole("textbox", { name: /Ngày quyết định/ })).not.toHaveAttribute("aria-invalid", "true");
  await expect(page.getByRole("textbox", { name: /Ngày hiệu lực/ })).not.toHaveAttribute("aria-invalid", "true");
  await expect(page.getByText("Bắt buộc nhập.", { exact: true })).toHaveCount(0);
  await page.screenshot({ path: info.outputPath("save-version194.png"), fullPage: true });
  await page.getByRole("main").getByRole("link", { name: "Kế hoạch năm", exact: true }).click();
  await expect(page.getByRole("row").filter({ hasText: "Hạng mục kế hoạch194" })).toBeVisible();
  await page.getByRole("button", { name: "Điều chỉnh theo QĐ", exact: true }).click();
  await expect(number).toHaveValue("QĐ194");
  await page.getByRole("button", { name: "Lưu phiên bản", exact: true }).click();
  await expect(page).toHaveURL(/\/phien-ban\/2\?year=2030$/);
  await expect(page.getByRole("heading", { name: "Kế hoạch năm 2030 — phiên bản 2", exact: true })).toBeVisible();
  await expect(page.getByRole("complementary", { name: "Log", exact: true })).toContainText("Điều chỉnh kế hoạch v2");
  await expect(page.getByRole("table", { name: "Các chương trình", exact: true }).getByText("Hạng mục kế hoạch194", { exact: true })).toBeVisible();
  await page.getByRole("link", { name: "Lịch sử phiên bản", exact: true }).click();
  const history = page.getByRole("table", { name: "Lịch sử kế hoạch năm", exact: true });
  await expect(history.getByRole("columnheader", { name: "STT", exact: true })).toBeVisible();
  await history.getByRole("link", { name: "Xem phiên bản 1", exact: true }).click();
  await expect(page).toHaveURL(/\/phien-ban\/1\?year=2030$/);
  await expect(page.getByText("Hạng mục kế hoạch194", { exact: true })).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Lưu phiên bản", exact: true })).toHaveCount(0);
  await expect(page.getByRole("complementary", { name: "Log", exact: true })).toContainText("Lập kế hoạch v1");
  await page.getByRole("link", { name: "Lịch sử phiên bản", exact: true }).click();
  await page.getByRole("main").getByRole("link", { name: "Kế hoạch năm", exact: true }).click();
  await expect(page).toHaveURL(`${base}?year=2030`);
  await expect(page.getByRole("row").filter({ hasText: "Hạng mục kế hoạch194" })).toBeVisible();
  await expect(page.getByRole("button", { name: "Điều chỉnh theo QĐ", exact: true })).toBeDisabled();
});

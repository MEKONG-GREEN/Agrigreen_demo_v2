import { expect, test } from "@playwright/test";
import { logout, sidebar } from "./helpers";

test("KHTC206: tạo CTDA, nhóm và hạng mục trên route riêng, số chính xác và snapshot", async ({ page }, info) => {
  test.setTimeout(180_000);
  await page.clock.setFixedTime(new Date("2030-06-01T09:00:00Z"));
  const login = async () => {
    await page.getByLabel("Email hoặc số điện thoại").fill("admin.mekong@mekonggreen.vn");
    await page.getByLabel("Mật khẩu", { exact: true }).fill("KhuyenNong@2026");
    await page.getByRole("button", { name: "Đăng nhập", exact: true }).click();
  };
  await page.goto("/login"); await login();
  await sidebar(page).getByRole("link", { name: "Phòng ban", exact: true }).click();
  await page.getByLabel("Trạng thái Phòng Kế hoạch - Tài chính", { exact: true }).selectOption("active");
  await expect(page.getByRole("status").filter({ hasText: "Đã đổi" })).toBeVisible();
  await logout(page); await login();
  await sidebar(page).getByRole("button", { name: "Phòng Kế hoạch - Tài chính", exact: true }).click();
  await sidebar(page).getByRole("link", { name: "Kế hoạch năm", exact: true }).click();
  await expect(page).toHaveURL(/\/ke-hoach-nam$/);
  const base = new URL(page.url()).pathname;
  await page.getByRole("button",{name:"Thêm CT/DA vào tab",exact:true}).click();
  await expect(page).toHaveURL(/\/chon-chuong-trinh\?year=2030&tab=programs$/);
  await page.getByRole("button",{name:"CT/DA mới…",exact:true}).click();
  await expect(page).toHaveURL(/\/chuong-trinh-moi\?year=2030&tab=programs$/);
  await page.getByRole("button",{name:"Lưu CT/DA chủ",exact:true}).click();
  await expect(page.getByRole("textbox",{name:/Mã CT\/DA/})).toHaveAttribute("aria-invalid","true");
  await page.getByRole("textbox",{name:/Mã CT\/DA/}).fill("CT206");
  await page.getByRole("textbox",{name:/Tên CT\/DA/}).fill("Chương trình thử206");
  await page.getByRole("button",{name:"Lưu CT/DA chủ",exact:true}).click();
  await page.getByRole("button",{name:"Chọn CT206",exact:true}).click();
  const program=page.getByRole("row").filter({hasText:"Chương trình thử206"});
  await program.getByRole("button",{name:"+ Nhóm",exact:true}).click();
  await expect(page).toHaveURL(/\/them-noi-dung\?/);
  await page.getByRole("textbox",{name:/^Tên/}).fill("Nhóm kiểm chứng206");
  await page.getByRole("button",{name:"Lưu vào nháp",exact:true}).click();
  const group=page.getByRole("row").filter({hasText:"Nhóm kiểm chứng206"});
  await group.getByRole("button",{name:"+ Hạng mục",exact:true}).click();
  await page.getByRole("textbox",{name:/^Tên/}).fill("Hạng mục kiểm chứng206");
  await page.getByRole("combobox",{name:/Phòng phụ trách/}).selectOption("trong_trot");
  for(const label of ["Thứ tự trong cây","Khối lượng KH","Kinh phí KH (đồng)","Số điểm"])await page.getByRole("textbox",{name:label,exact:true}).fill("1e100000");
  await page.getByRole("button",{name:"Lưu vào nháp",exact:true}).click();
  for(const label of ["Thứ tự trong cây","Khối lượng KH","Kinh phí KH (đồng)","Số điểm"])await expect(page.getByRole("textbox",{name:label,exact:true})).toHaveAttribute("aria-invalid","true");
  await page.screenshot({path:info.outputPath("entry206-numeric-errors.png"),fullPage:true});
  await page.getByRole("textbox",{name:"Thứ tự trong cây",exact:true}).fill("10");
  await page.getByRole("textbox",{name:"Khối lượng KH",exact:true}).fill("123,0001");
  await page.getByRole("textbox",{name:"Kinh phí KH (đồng)",exact:true}).fill("999999999999999999.99");
  await page.getByRole("textbox",{name:"Số điểm",exact:true}).fill("2");
  await page.getByRole("button",{name:"Lưu vào nháp",exact:true}).click();
  await expect(page.getByRole("row").filter({hasText:"Hạng mục kiểm chứng206"})).toContainText("123,0001");
  await page.getByRole("button",{name:"Điều chỉnh theo QĐ",exact:true}).click();
  await page.getByRole("textbox",{name:/Số quyết định/}).fill("QD206");
  await page.getByRole("textbox",{name:/Ngày quyết định/}).fill("2030-06-01");
  await page.getByRole("textbox",{name:/Ngày hiệu lực/}).fill("2030-07-01");
  await page.getByRole("button",{name:"Lưu phiên bản",exact:true}).click();
  await expect(page).toHaveURL(/\/phien-ban\/2\?year=2030$/);
  await expect(page.getByRole("row").filter({hasText:"Hạng mục kiểm chứng206"})).toContainText("123,0001");
  await expect(page.getByRole("button",{name:"Sửa",exact:true})).toHaveCount(0);
  await expect(page.getByRole("complementary",{name:"Log",exact:true})).toContainText("Điều chỉnh kế hoạch v2");
  await expect(page.getByRole("tab")).toHaveCount(6);
  await page.screenshot({path:info.outputPath("snapshot206-tree-log.png"),fullPage:true});
  await page.getByRole("link",{name:"Lịch sử phiên bản",exact:true}).click();
  await page.getByRole("link",{name:"Xem phiên bản 1",exact:true}).click();
  await expect(page.getByText("Hạng mục kiểm chứng206",{exact:true})).toHaveCount(0);
  await expect(page.getByText("Mô hình lúa chất lượng cao",{exact:true})).toBeVisible();
  await expect(page.getByRole("button",{name:"Sửa",exact:true})).toHaveCount(0);
});

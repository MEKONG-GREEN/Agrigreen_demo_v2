import { expect, test } from "@playwright/test";
import { MOCK_KN_PASSWORD } from "../../src/api/mock/kn-accounts";
import { logout, sidebar } from "./helpers";

test("241 reviewer: đúng phòng, chỉ đọc nguồn, ghi chú và xác nhận đúng lần gửi", async ({ page }, testInfo) => {
  test.setTimeout(180_000);
  await page.clock.setFixedTime(new Date("2030-06-01T09:00:00Z"));
  const login = async (identifier: string) => {
    await page.getByLabel("Email hoặc số điện thoại").fill(identifier);
    await page.getByLabel("Mật khẩu", { exact: true }).fill(MOCK_KN_PASSWORD);
    await page.getByRole("button", { name: "Đăng nhập", exact: true }).click();
  };
  await page.goto("/login"); await login("admin.mekong@mekonggreen.vn");
  await sidebar(page).getByRole("link", { name: "Phòng ban", exact: true }).click();
  await page.getByLabel("Trạng thái Phòng Kế hoạch - Tài chính", { exact: true }).selectOption("active");
  await expect(page.getByRole("status").filter({ hasText: "Đã đổi" })).toBeVisible();
  // Phân công thật qua Admin UI; không giả header, API ngầm hoặc sửa storage quyền.
  await sidebar(page).getByRole("link", { name: "Người dùng", exact: true }).click();
  await page.getByRole("link", { name: "Tạo tài khoản", exact: true }).click();
  const main = page.getByRole("main");
  await expect(main.getByRole("button", { name: "Lưu", exact: true })).toBeEnabled();
  await main.getByLabel("Họ tên").fill("Cán bộ KHTC kiểm thử 241");
  await main.getByLabel("Email").fill("khtc.review241@example.test");
  await main.getByLabel("Số điện thoại (tên đăng nhập)").fill("0912345241");
  const assignment = main.getByRole("group", { name: "Vai trò và phạm vi" });
  await assignment.getByRole("combobox", { name: "Vai trò", exact: true }).selectOption("kn_tinh");
  await assignment.getByRole("checkbox", { name: "trong_trot", exact: true }).uncheck();
  await assignment.getByRole("checkbox", { name: "ke_hoach_tai_chinh", exact: true }).check();
  await expect(main.getByLabel("Họ tên")).toHaveValue("Cán bộ KHTC kiểm thử 241");
  await main.getByRole("button", { name: "Lưu", exact: true }).click();
  await expect(page.getByRole("heading", { level: 1, name: "Cán bộ KHTC kiểm thử 241" })).toBeVisible();
  await logout(page); await login("0912345241");
  const periods = page.getByRole("table", { name: "Danh sách kỳ báo cáo", exact: true });
  await periods.locator('a[href*="/kn/khtc/ky-bao-cao/ky/"]').first().click();
  const progress = page.getByRole("table", { name: "Tiến độ nộp phiếu và nguồn module", exact: true });
  await progress.getByRole("row").filter({ hasText: "Phòng Trồng trọt" }).getByRole("link", { name: "Rà soát", exact: true }).click();
  await expect(page.getByRole("heading", { level: 1, name: /Rà soát phiếu Phòng Trồng trọt/ })).toBeVisible();
  await expect(page.getByRole("heading", { level: 1 })).toHaveCSS("font-family", /Noto Serif/);
  await expect(page.getByRole("button", { name: "Yêu cầu bổ sung", exact: true })).toHaveClass(/btn-p(?:\s|$)/);
  const confirmBox = await page.getByRole("button", { name: "Xác nhận", exact: true }).boundingBox();
  expect(confirmBox?.x).toBeGreaterThan(page.viewportSize()!.width * 0.65);
  const note = page.getByRole("textbox", { name: /Nội dung yêu cầu bổ sung/ });
  await expect(page.getByRole("textbox")).toHaveCount(1);
  await page.getByRole("button", { name: "Yêu cầu bổ sung", exact: true }).click();
  await expect(note).toHaveAttribute("aria-invalid", "true");
  await expect(note).toBeFocused();
  await page.screenshot({ path: testInfo.outputPath("241-review-note-required.png"), fullPage: true });
  await note.fill("Ghi chú riêng của Trồng trọt");
  await page.getByRole("button", { name: "Phiếu tiếp theo", exact: true }).click();
  await page.getByRole("dialog", { name: "Bỏ ghi chú chưa gửi?" }).getByRole("button", { name: "Bỏ ghi chú và chuyển", exact: true }).click();
  await expect(page.getByRole("heading", { level: 1, name: /Chăn nuôi/ })).toBeVisible();
  await expect(page.getByText("Ghi chú riêng của Trồng trọt", { exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Phiếu trước", exact: true }).click();
  await note.fill("Bổ sung diện tích thực hiện đã đối chiếu với kế hoạch.");
  await page.getByRole("button", { name: "Yêu cầu bổ sung", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "Xác nhận yêu cầu bổ sung" });
  await expect(dialog).toContainText("lần gửi 1");
  await expect(dialog).toContainText("Bổ sung diện tích thực hiện");
  await expect(dialog).toBeFocused();
  const dialogBox = await dialog.boundingBox();
  const pickerBox = await page.getByRole("combobox", { name: "Phòng được giao phiếu" }).boundingBox();
  expect(dialogBox).not.toBeNull(); expect(pickerBox).not.toBeNull();
  expect(dialogBox!.y + dialogBox!.height).toBeLessThan(pickerBox!.y);
  await page.screenshot({ path: testInfo.outputPath("241-review-confirmation.png"), fullPage: true });
  await dialog.getByRole("button", { name: "Gửi yêu cầu bổ sung", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "Đã gửi yêu cầu bổ sung cho lần gửi 1." })).toBeVisible();
  await expect(page.getByRole("textbox")).toHaveCount(0);
  await expect(page.getByRole("alert").filter({ hasText: "Yêu cầu bổ sung: Bổ sung diện tích thực hiện đã đối chiếu với kế hoạch." })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("241-review-ack.png"), fullPage: true });
});

package domain

import (
	"fmt"
	"github.com/MEKONG-GREEN/Agrigreen_demo_v2/internal/kn/extension/port"
	"github.com/google/uuid"
	"github.com/shopspring/decimal"
	"math/big"
	"regexp"
	"sort"
	"time"
)

var dashboardNumber = regexp.MustCompile(`^-?[0-9]+(?:\.[0-9]+)?$`)

// DashboardProgress uses the exact same captured Mẫu 5 rows, never a saved draft.
type DashboardProgress struct {
	Items    int                `json:"items"`
	Achieved int                `json:"achieved"`
	Slow     int                `json:"slow"`
	Missing  int                `json:"missing"`
	Programs []DashboardProgram `json:"programs"`
	Rows     []ProgramRow       `json:"rows"`
}
type DashboardProgram struct {
	Ref     uuid.UUID `json:"ref"`
	Name    string    `json:"name"`
	Items   int       `json:"items"`
	Known   int       `json:"known"`
	Percent *string   `json:"percent"`
}

// SummarizeDashboard excludes unclosed/missing sources from achievement and averages.
// Quantitative items without data stay visible as missing, not fabricated zeroes.
// Average is computed from unrounded ratios, rounded only once at the output boundary.
func SummarizeDashboard(data Data, department, field string, now time.Time) (DashboardProgress, error) {
	out := DashboardProgress{Programs: []DashboardProgram{}, Rows: []ProgramRow{}}
	entries := map[uuid.UUID]port.KHTCPlanEntry{}
	for _, e := range data.Plan.Entries {
		entries[e.Ref] = e
	}
	roots := map[uuid.UUID]DashboardProgram{}
	sums := map[uuid.UUID]*big.Rat{}
	for _, row := range data.Rows {
		if row.Kind != "item" || row.Tab != "programs" || (department != "" && row.Department != department) {
			continue
		}
		entry, ok := entries[row.Ref]
		if !ok {
			continue
		}
		root := entry
		fieldCode := entry.FieldCode
		for depth := 0; root.ParentRef != nil && depth < 16; depth++ {
			p, ok := entries[*root.ParentRef]
			if !ok {
				break
			}
			root = p
			if fieldCode == "" {
				fieldCode = p.FieldCode
			}
		}
		if field != "" && fieldCode != field {
			continue
		}
		out.Rows = append(out.Rows, row)
		if entry.PlannedQty == nil || !entry.PlannedQty.IsPositive() {
			continue
		}
		out.Items++
		program := roots[root.Ref]
		program.Ref, program.Name = root.Ref, root.Name
		program.Items++
		if row.Missing {
			out.Missing++
			roots[root.Ref] = program
			continue
		}
		// Captured totals are generated by Compose from bounded inputs. Bound the
		// serialized value as defense against corrupted stored snapshots.
		if len(row.YearToDate) > 128 || !dashboardNumber.MatchString(row.YearToDate) {
			return DashboardProgress{}, fmt.Errorf("%w: dashboard total too long", ErrInput)
		}
		total, err := decimal.NewFromString(row.YearToDate)
		if err != nil {
			return DashboardProgress{}, ErrInput
		}
		percent := new(big.Rat).Quo(total.Mul(decimal.NewFromInt(100)).Rat(), entry.PlannedQty.Rat())
		program.Known++
		if sums[root.Ref] == nil {
			sums[root.Ref] = new(big.Rat)
		}
		sums[root.Ref].Add(sums[root.Ref], percent)
		if total.GreaterThanOrEqual(*entry.PlannedQty) {
			out.Achieved++
		}
		threshold := time.Date(data.Period.Year, 10, 1, 0, 0, 0, 0, now.Location())
		if !now.Before(threshold) && total.Mul(decimal.NewFromInt(100)).LessThan(entry.PlannedQty.Mul(decimal.NewFromInt(30))) {
			out.Slow++
		}
		roots[root.Ref] = program
	}
	for id, p := range roots {
		if p.Known > 0 {
			mean := new(big.Rat).Quo(sums[id], big.NewRat(int64(p.Known), 1))
			v := decimal.NewFromBigInt(mean.Num(), 0).DivRound(decimal.NewFromBigInt(mean.Denom(), 0), 2).String()
			p.Percent = &v
		}
		out.Programs = append(out.Programs, p)
	}
	sort.Slice(out.Programs, func(i, j int) bool { return out.Programs[i].Ref.String() < out.Programs[j].Ref.String() })
	return out, nil
}

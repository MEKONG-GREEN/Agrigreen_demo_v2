package modreg

// Ghép module theo đơn vị triển khai lúc chạy (W2.3, ADR-0028): modgen sinh assembly_gen.go từ import
// của cmd/<đơn vị> (cùng phép tính với cổng W1.3 Apps.CheckAssembly). dbadmin dùng để cho vai đăng nhập
// app_<đơn vị> làm thành viên các r_<module> của module ghép trong đơn vị đó.

import (
	"bytes"
	"fmt"
	"go/format"
	"slices"
	"strconv"
	"strings"
)

// AssemblyFile là đường dẫn (tương đối gốc repo) của tệp ghép module sinh.
const AssemblyFile = "internal/shared/modreg/assembly_gen.go"

// UnitModules trả các module được ghép TRONG TIẾN TRÌNH của cmd/<unit> (đã sắp theo tên, bản sao);
// nil khi đơn vị không có.
func UnitModules(unit string) []string { return slices.Clone(assembly[unit]) }

// Units trả các đơn vị triển khai có trong tệp ghép sinh (đã sắp).
func Units() []string {
	out := make([]string, 0, len(assembly))
	for u := range assembly {
		out = append(out, u)
	}
	slices.Sort(out)
	return out
}

// DBRole trả vai nhóm NOLOGIN của module (ADR-0028): r_<đoạn cuối tên>, vd pf/content → r_content.
// Tên vai suy từ tên module trong module.yaml, mã nghiệp vụ không truyền tên vai (R-DB-03).
func DBRole(module string) string {
	_, seg, ok := strings.Cut(module, "/")
	if !ok {
		seg = module
	}
	return "r_" + seg
}

// FormatAssembly sinh nội dung assembly_gen.go (đã gofmt) từ đơn vị → module.
func FormatAssembly(wired map[string][]string) ([]byte, error) {
	units := make([]string, 0, len(wired))
	for u := range wired {
		units = append(units, u)
	}
	slices.Sort(units)
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/modgen; DO NOT EDIT.\n\n")
	b.WriteString("package modreg\n\n")
	b.WriteString("var assembly = map[string][]string{\n")
	for _, u := range units {
		mods := slices.Clone(wired[u])
		slices.Sort(mods)
		q := make([]string, len(mods))
		for i, m := range mods {
			q[i] = strconv.Quote(m)
		}
		fmt.Fprintf(&b, "\t%s: {%s},\n", strconv.Quote(u), strings.Join(q, ", "))
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

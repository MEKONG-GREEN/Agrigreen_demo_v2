package modreg

// Danh mục module lúc chạy (W1.4, R-MOD-08): nhị phân không mang module.yaml theo, nên modgen
// sinh catalog_gen.go từ các tệp khai báo (tên, tầng, chính sách bật, vai). `go run ./tools/modgen
// -check` hỏng khi tệp sinh lệch module.yaml.

import (
	"bytes"
	"fmt"
	"go/format"
	"slices"
	"strconv"
	"strings"
)

// CatalogFile là đường dẫn (tương đối gốc repo) của tệp danh mục sinh.
const CatalogFile = "internal/shared/modreg/catalog_gen.go"

// CatalogEntry là phần module.yaml cần lúc chạy.
type CatalogEntry struct {
	Name        string
	Kind        Kind
	Enable      Enable
	Permissions []string // vai realm module khai (permissions)
	// Zones: cụm dữ liệu module chạy (zones) — W2.6: cụm của vai nhóm r_<module> (dbadmin).
	Zones []string
	// OwnsSchema: schema module sở hữu (owns_schema) — W2.6: module có schema thì có vai nhóm r_<module>.
	OwnsSchema []string
	// Shares: bảng chia sẻ được (shares, ADR-0030) — tên logic, đã sắp (W4.1: kiểm module_table của cấp phép).
	Shares []string
}

// Catalog trả mọi module theo tên (bản sao).
func Catalog() []CatalogEntry {
	out := make([]CatalogEntry, len(catalog))
	for i, e := range catalog {
		out[i] = e.clone()
	}
	return out
}

func (e CatalogEntry) clone() CatalogEntry {
	e.Permissions = slices.Clone(e.Permissions)
	e.Zones = slices.Clone(e.Zones)
	e.OwnsSchema = slices.Clone(e.OwnsSchema)
	e.Shares = slices.Clone(e.Shares)
	return e
}

// Entry trả mục danh mục của một module.
func Entry(name string) (CatalogEntry, bool) {
	for _, e := range catalog {
		if e.Name == name {
			return e.clone(), true
		}
	}
	return CatalogEntry{}, false
}

// PerTenant cho biết module có tồn tại và bật/tắt được theo đơn vị (enable: per_tenant).
func PerTenant(name string) bool {
	e, ok := Entry(name)
	return ok && e.Enable == EnablePerTenant
}

// Shared cho biết module khai share trong shares của module.yaml (ADR-0030, R-DB-08): chỉ bảng khai ở
// đây mới được cấp phép chia sẻ intra_platform (pf/party, W4.1) và mang nhánh share_scope (W4.2).
func Shared(module, share string) bool {
	e, ok := Entry(module)
	return ok && share != "" && slices.Contains(e.Shares, share)
}

// ShareTable ánh xạ tên logic "<module>:<share>" của cấp phép intra_platform (pf/party, W4.1) sang khóa
// module_table của k_ref.share_scope và của chính sách p_share (W4.2): "<schema chính>.<share>", schema chính
// là schema đầu tiên của owns_schema (vd pf/cooperative:household → pf_coop.household, pf/mechanization:machine
// → pf_mechanization.machine). Khóa là tên của share, không nhất thiết là một bảng vật lý (pf_coop.season phủ
// season_current, coop_season_area, yield_summary — docs/design/cooperative.md §7.3). Share không khai → false.
func ShareTable(moduleTable string) (string, bool) {
	module, share, ok := strings.Cut(moduleTable, ":")
	if !ok || !Shared(module, share) {
		return "", false
	}
	e, _ := Entry(module)
	if len(e.OwnsSchema) == 0 {
		return "", false
	}
	return e.OwnsSchema[0] + "." + share, true
}

// ShareTables trả mọi ánh xạ tên logic → khóa share_scope của danh mục (xem ShareTable).
func ShareTables() map[string]string {
	out := map[string]string{}
	for _, e := range catalog {
		for _, s := range e.Shares {
			if k, ok := ShareTable(e.Name + ":" + s); ok {
				out[e.Name+":"+s] = k
			}
		}
	}
	return out
}

// RoleModules trả các module khai vai role trong permissions (đã sắp theo tên).
func RoleModules(role string) []string {
	var out []string
	for _, e := range catalog {
		if slices.Contains(e.Permissions, role) {
			out = append(out, e.Name)
		}
	}
	return out
}

// RoleBlocked cho biết vai role KHÔNG cấp được khi các module trong disabled đã tắt: mọi module khai
// vai đều là per_tenant và đều đã tắt. Vai không module nào khai (vd platform_admin) hoặc có ít nhất
// một module luôn bật / còn bật khai thì cấp được.
func RoleBlocked(role string, disabled func(module string) bool) (blocked bool, modules []string) {
	mods := RoleModules(role)
	if len(mods) == 0 {
		return false, nil
	}
	for _, m := range mods {
		if !PerTenant(m) || !disabled(m) {
			return false, nil
		}
	}
	return true, mods
}

// FormatCatalog sinh nội dung catalog_gen.go (đã gofmt) từ các manifest.
func FormatCatalog(mods []*Manifest) ([]byte, error) {
	sorted := slices.Clone(mods)
	slices.SortFunc(sorted, func(a, b *Manifest) int { return strings.Compare(a.Name, b.Name) })
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/modgen; DO NOT EDIT.\n\n")
	b.WriteString("package modreg\n\n")
	b.WriteString("var catalog = []CatalogEntry{\n")
	for _, m := range sorted {
		perms := slices.Clone(m.Permissions)
		slices.Sort(perms)
		shares := slices.Clone(m.Shares)
		slices.Sort(shares)
		fmt.Fprintf(&b, "\t{Name: %s, Kind: %s, Enable: %s, Permissions: %s, Zones: %s, OwnsSchema: %s, Shares: %s},\n",
			strconv.Quote(m.Name), strconv.Quote(string(m.Kind)), strconv.Quote(string(m.Enable)),
			goStrings(perms), goStrings(m.Zones), goStrings(m.OwnsSchema), goStrings(shares))
	}
	b.WriteString("}\n")
	// W7.1 (R-DB-12): phụ thuộc module cho bộ chạy migration v2 (thứ tự topo) — biến riêng ở cuối tệp để gộp
	// nhánh ít đụng các dòng danh mục ở trên.
	b.WriteString("\nvar catalogDepends = map[string][]string{\n")
	for _, m := range sorted {
		if deps := m.DependNames(); len(deps) > 0 {
			fmt.Fprintf(&b, "\t%s: %s,\n", strconv.Quote(m.Name), strings.TrimPrefix(goStrings(deps), "[]string"))
		}
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

// Depends trả các module mà name khai trong depends của module.yaml (đã sắp; nil nếu không có) — W7.1: bộ
// chạy migration v2 (internal/shared/migrator) xếp thứ tự topo theo đồ thị này lúc chạy, không cần module.yaml.
func Depends(name string) []string { return slices.Clone(catalogDepends[name]) }

func goStrings(xs []string) string {
	q := make([]string, len(xs))
	for i, x := range xs {
		q[i] = strconv.Quote(x)
	}
	return "[]string{" + strings.Join(q, ", ") + "}"
}
